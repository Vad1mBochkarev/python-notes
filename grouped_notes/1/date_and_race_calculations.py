# Время, место и дата проведения соревнований согласованы, теперь стоит позаботиться о комфорте участников.

# После состязаний каждому участнику должно приходить сообщение, в котором будет
#     - время, за которое участник прошёл дистанцию — в формате ЧЧ:ММ:СС;
#     - время, на которое участник отстал от лидера — в формате Ч:ММ:СС.

# Напишите функцию get_results(), которая принимает время лидера и время участника в формате ЧЧ:ММ:СС,
# находит разницу между этими значениями и печатает сообщение:
#     'Вы пробежали за ЧЧ:ММ:СС с отставанием от лидера Ч:ММ:СС'
# Если же сообщение отправляется лидеру, оно должно быть таким:
#     'Вы пробежали за ЧЧ:ММ:СС и победили!'

from datetime import datetime

def get_results(leader, player):
    date_f = '%H:%M:%S'

    delta = datetime.strptime(player, date_f) - datetime.strptime(leader, date_f)

    if (player == leader):
        print('Вы пробежали за', leader ,'и победили!')
    else:
        print('Вы пробежали за', player ,'с отставанием от лидера', delta)

