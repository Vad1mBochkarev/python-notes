# Соревнования от бегового клуба RockRun снискали успех, и было принято решение масштабироваться.
# Для масштабирования нужны деньги, поэтому команда клуба будет брать кредит в ВотКоинах в Это.Банке.

# Система расчёта ежемесячных платежей в Это.Банке такова:
# 1. Клиент называет сумму и количество месяцев, за которые планирует выплатить кредит.
# 2. Банк делит названную сумму на названное количество месяцев и увеличивает ежемесячный платёж на оговоренный процент.

# Помогите команде клуба разобраться, сколько ВотКоинов им нужно платить каждый месяц,
# если они планируют взять кредит 54 ВтК на 24 месяца с месячной ставкой 9%.

# Для этого напишите функцию get_monthly_payment(), которая будет принимать три параметра:
#  - сумму кредита;
#  - количество месяцев, за которые клиент планирует выплатить кредит;
#  - процент банка.

# Функция должна вернуть сумму ежемесячного платежа по кредиту.
# Информацию нужно распечатать в следующем виде:
# 'Ежемесячный платёж: <сумма> ВтК'


def get_monthly_payment(money, month, percent):
    x = money / month
    x = x + x * (percent / 100)
    return round(x, 2)

print("Ежемесячный платёж:", get_monthly_payment(54, 24, 9), "ВтК")


