# Для этого напишите две функции:
#  - get_weekday_name() — должна принимать номер дня недели и возвращать название этого дня по-русски, с маленькой буквы. Дни недели нумеруются от 0 до 6.
#  - get_day_after_tomorrow() — должна принимать строку в формате ГГГГ-ММ-ДД и возвращать такое сообщение:
#             "Сегодня <дата>, <день недели сегодня>, а послезавтра будет <день недели послезавтра>"

from datetime import datetime
from datetime import timedelta

def get_weekday_name(weekday_number):
    weekday = {
       0 : 'понедельник',
       1 : 'вторник',
       2 : 'среда',
       3 : 'четверг',
       4 : 'пятница',
       5 : 'суббота',
       6 : 'воскресенье',
    }
    return weekday[weekday_number]


def get_day_after_tomorrow(date_string):
    date_format = '%Y-%m-%d'

    date1 = datetime.strptime(date_string, date_format)

    date2 = date1 + timedelta(days=2)

    x = date2.weekday()

    print("Сегодня", get_weekday_name(date1.weekday()) + ", а послезавтра будет", get_weekday_name(x))


