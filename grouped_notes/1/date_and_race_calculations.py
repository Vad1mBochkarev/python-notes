# ЗАДАНИЕ 3
# Фермер Тоня хочет узнать, сколько дней прошло с начала посевной до начала сбора урожая.
# Напишите программу, которая поможет рассчитать количество дней между двумя датами.
# Допишите код функции timedelta_days(),
# которая принимает в качестве аргументов две строки с датами в формате '%Y/%m/%d %H:%M:%S',
# например '2008/08/10 00:00:00', и возвращает количество дней между этими датами.
# Ваша программа должна вернуть целое число дней, без плавающей точки.

from datetime import datetime

def timedelta_days(datetime_str_1, datetime_str_2):
    date_format = '%Y/%m/%d %H:%M:%S'

    date1 = datetime.strptime(datetime_str_1, date_format)
    date2 = datetime.strptime(datetime_str_2, date_format)
    
    x = date2 - date1

    return x.days

difference = timedelta_days('2019/05/10 00:00:00', '2019/10/04 00:00:00')

print('От начала посевной до начала сбора урожая прошло', difference, 'дней.')


