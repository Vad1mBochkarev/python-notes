import sys


def binar_search(sorted_numbers, element):
    """Функция бинарного поиска"""
    left = 0
    right = len(sorted_numbers)               # до len(), а не len()-1

    while left < right:                       # <, а не <=
        mid = (left + right) // 2
        if sorted_numbers[mid] < element:
            left = mid + 1
        else:
            right = mid
    return left                                # Возвращаем индекс элемента (или вставки)


