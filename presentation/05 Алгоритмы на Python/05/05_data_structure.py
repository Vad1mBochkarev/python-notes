# Во время марсианских гроз ровер Impunity должен работать как «умный громоотвод» — ловить разряды молний,
# замерять их напряжение и сохранять полученные данные в массив.

# Очередной раз попав в грозу, ровер должен замерить напряжение каждой новой молнии,
# которая в него ударит, и проверить, есть ли такое значение в его коллекции записей.
# Если есть — отметить это на счётчике.
# В результате он сосчитает, сколько новых молний совпадают по напряжению с теми, что уже записаны.
# Метеорологам это зачем-то нужно.

# Сгенерируем коллекцию data, в ней будет 10 000 случайных чисел в диапазоне от 1 до 10 000 000.
# Это будет коллекция записей о прошлых молниях.
# Значения «новых ударов молний» случайным образом будем генерировать в цикле;
# эти значения будем искать в коллекции data. Предположим, что ровер попал в очень большую грозу,
# и в него попало 10 000 молний;
# значит, цикл должен сгенерировать 10 000 случайных чисел и проверить наличие каждого из них в массиве data.


# При выполнении кода измерим время, за которое он выполняется.
# В стандартной библиотеке Python в модуле time есть функция time(), она получает текущее время.
# С её помощью засечём время выполнения кода.

# Чтобы увидеть, сколько времени занимают разные этапы программы — расставим в коде print().
import time
# Импортируем функцию randint - с её помощью сгенерируем набор случайных чисел.
from random import randint

# Засекаем время начала работы.
start_time = time.time()

# Количество элементов в коллекции data:
DATA_SIZE = 10000
# Максимальное значение случайного числа при генерации коллекции data:
MAX_RAND_NUMBER = 10000000

# В цикле генерируем список случайных чисел в диапазоне от 1 до 10 млн.
# Вместо имени переменной цикла ставим символ "_",
# ведь в теле цикла эта переменная не применяется.
data = [randint(1, MAX_RAND_NUMBER) for _ in range(DATA_SIZE)]

# Печатаем, сколько времени генерировался список data:
print(f'Коллекция data сгенерирована за {time.time() - start_time} сек.')

# Счётчик совпадающих элементов.
match_counter = 0

# Генерируем в цикле "новые удары молний" - случайные значения.
# Таких значений будет 10 000:
for _ in range(10000):
    # Генерируем случайное значение:
    new_item = randint(1, MAX_RAND_NUMBER)
    # Ищем полученное значение в массиве data...
    if new_item in data:
        # ...и если нашли - увеличиваем счётчик совпадающих элементов.
        match_counter += 1

# Печатаем результаты поиска:
print(f'Найдено совпадений: {match_counter}')
# Для наглядности печатаем число элементов в коллекции data:
print(f'Объектов в data: {len(data)}')
# Печатаем, сколько времени работала программа.
print(f'Программа отработала за {time.time() - start_time} сек.')
# Коллекция data сгенерирована за 0.008143186569213867 сек.
# Найдено совпадений: 6
# Объектов в data: 10000
# Программа отработала за 0.9655444622039795 сек. 







