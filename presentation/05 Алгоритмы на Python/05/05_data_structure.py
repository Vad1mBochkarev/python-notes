# Полмиллиона элементов множества обработаны в сто раз быстрее, чем список той же длины! 

# Изменение структуры, в которой хранятся данные, привело к выигрышу по времени в 100 раз!
# Причина в том, что для поиска элемента во множестве работает не линейный поиск,
# а применяется другой алгоритм, который работает за константное время O(1). 




