# РЕШЕНИЕ
def is_correct_bracket_seq(bracket_seq):
    """Функция проверки скобок"""
    stack = []

    for item in bracket_seq:
        if item == '(' or item == '{' or item == '[':
            stack.append(item)
            continue
        if stack != []:
            last_item = stack.pop()
            if last_item + item == '()' \
                    or last_item + item == '[]' \
                    or last_item + item == '{}':
                continue
            else:
                return False
        else:
            return False
    if stack == []:
        return True
    else:
        return False


def main():
    """Основная функция"""
    bracket_seq = list(input())
    print(is_correct_bracket_seq(bracket_seq))


if __name__ == "__main__":
    main()
